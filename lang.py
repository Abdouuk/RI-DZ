def get_text(key: str, lang: str = "ar", **kwargs) -> str:
    lang_code = lang if lang in TRANSLATIONS else "ar"
    template = TRANSLATIONS[lang_code].get(key) or TRANSLATIONS["ar"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
